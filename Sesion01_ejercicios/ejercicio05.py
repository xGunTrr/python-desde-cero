# 5. Calculadora de edad futura
# Pide al usuario:
# Nombre:
# Edad:
# Después muestra cuántos años tendrá esa persona dentro de 5, 10 y 20 años.
# Objetivo: combinar strings, enteros, conversiones y suma.
nombre = input("ingrese el nombre:" )
edad = int (input("ingrese la edad: "))

print (f"el nombre es :{nombre}")
# 5 años


print (f" la edad en 5 años : { edad + 5}" )

# 10 años
print (f"la edad en 10 años: { edad + 10}")

# 20 años

print(f"la edad en 20 años: {edad + 20}")