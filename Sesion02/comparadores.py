# Calcular mayores y menores

# Mayor (>)
print(13 > 12) # True 

# Mayor igual (>=)
print(13 >= 13)

# Menor (<)
print(18 < 11) # False

# Menor igual (<=)
print(18 <= 18)

# Igual (==)
print(12 == 12) # True

# Diferente (!=)
print(12 != 12) # False

# y (and)
print(12 > 15 and 12 > 1)
# F and V = F
# o (or)
print(12 > 15 or 12 < 1)
# F or F = F